-- CONSULTA OPTIMIZADA CON SUBCONSULTAS Y MEJORES PRÁCTICAS
-- Versión optimizada que reduce el tiempo de carga

WITH transacciones_filtradas AS (
    -- Subconsulta para filtrar y agregar datos de transacciones
    SELECT 
        TRUNC(FECHA_TRANSACCION_D) AS FECHA_DATA_D,
        CODIGO_CAJERO_V,
        CODIGO_TRANSACCION_V,
        CODIGO_MONEDA_V,
        CODIGO_OFICINA_V,
        DEBITO_CREDITO_V,
        COUNT(NUMERO_TRANSACCION_N) AS QTY_TRANSACCION_N,
        SUM(MONTO_IMPORTE_N) AS SUMA_MONTO,
        COUNT(NUMERO_CUENTA_CLIENTE_V) AS QTY_CUENTA
    FROM DT_TRANSACCIONES.TRANSACCIONES_CAJA
    WHERE FECHA_TRANSACCION_D >= TRUNC(SYSDATE - 90)
    GROUP BY 
        TRUNC(FECHA_TRANSACCION_D),
        CODIGO_CAJERO_V,
        CODIGO_TRANSACCION_V,
        CODIGO_MONEDA_V,
        CODIGO_OFICINA_V,
        DEBITO_CREDITO_V
),
cajeros_activos AS (
    -- Subconsulta para obtener solo cajeros activos
    SELECT 
        CODIGO_CAJERO_V,
        CODIGO_CLASE_V,
        MARCA_SUPERVISOR_N,
        NOMBRE_CAJERO_V,
        SECTOR_CUENTA_N,
        CODIGO_USUARIO_V
    FROM DT_DIMENSIONES.DIM_CAJEROS
    WHERE FLAG_REGISTRO_ACTUAL_N = 1
),
monedas_core AS (
    -- Subconsulta para monedas del aplicativo CORE
    SELECT 
        CODIGO_MONEDA_APLICATIVO_V,
        CODIGO_MONEDA_V AS DESCRIPCION_MONEDA_V
    FROM DT_DIMENSIONES.DIM_MONEDAS_APLICATIVOS
    WHERE CODIGO_APLICATIVO_V = 'CORE'
)
SELECT 
    tf.FECHA_DATA_D,
    tf.CODIGO_CAJERO_V,
    tf.CODIGO_TRANSACCION_V,
    tt.DESCRIPCION_TRANSACCION_V,
    tt.CODIGO_TIPO_TRANSACION_V,
    tt.ABREVIATURA_TRANSACCION_V,
    tf.CODIGO_MONEDA_V,
    ofi.DESCRIPCION_TIPO_OFICINA_V,
    ofi.CODIGO_TIPO_OFICINA_V,
    mc.DESCRIPCION_MONEDA_V,
    tf.CODIGO_OFICINA_V,
    ofi.CODIGO_PROVINCIA_V,
    ofi.DESCRIPCION_PROVINCIA_V,
    ofi.DESCRIPCION_OFICINA_V,
    ofi.DESCRIPCION_ZONA_OFICINA_V,
    tf.DEBITO_CREDITO_V,
    caj.CODIGO_CLASE_V,
    caj.MARCA_SUPERVISOR_N,
    caj.NOMBRE_CAJERO_V,
    caj.SECTOR_CUENTA_N,
    caj.CODIGO_USUARIO_V,
    tf.QTY_TRANSACCION_N,
    tf.SUMA_MONTO,
    tf.QTY_CUENTA
FROM transacciones_filtradas tf
    LEFT JOIN cajeros_activos caj ON caj.CODIGO_CAJERO_V = tf.CODIGO_CAJERO_V
    LEFT JOIN DT_DIMENSIONES.DIM_TIPO_TRANSACCIONES_CAJA tt ON tt.CODIGO_TIPO_TRANSACION_V = tf.CODIGO_TRANSACCION_V
    LEFT JOIN monedas_core mc ON mc.CODIGO_MONEDA_APLICATIVO_V = tf.CODIGO_MONEDA_V
    LEFT JOIN DT_DIMENSIONES.DIM_OFICINAS ofi ON ofi.CODIGO_OFICINA_V = tf.CODIGO_OFICINA_V;

